namespace Soneso\StellarSDKTests\Unit\Xdr\Sep51;

use PHPUnit\Framework\TestCase;

/**
 * SEP-51 corpus provenance test.
 *
 * The committed corpus must come from the reference CLI build pinned in
 * tools/sep-51-test-fixtures/oracle-pin.json. The corpus records the build
 * that generated it in `_meta.oracle`, so a pin bump without regeneration,
 * or a regeneration with a build other than the pin, fails here.
 */
class CorpusOraclePinTest extends TestCase
{
    private const FIXTURES_DIR = __DIR__ . '/../../../../../tools/sep-51-test-fixtures';

    /**
     * @return array<string, mixed>
     */
    private static function loadJson(string $name): array
    {
        $raw = file_get_contents(self::FIXTURES_DIR . '/' . $name);
        self::assertNotFalse($raw, "failed to read $name");
        $decoded = json_decode($raw, true, 512, JSON_THROW_ON_ERROR);
        self::assertIsArray($decoded, "$name did not decode to a JSON object");
        return $decoded;
    }

    public function testCorpusRecordsThePinnedOracleBuild(): void
    {
        $pin = self::loadJson('oracle-pin.json');
        $oracle = self::loadJson('corpus.json')['_meta']['oracle'] ?? null;
        $this->assertIsArray($oracle, 'corpus.json has no _meta.oracle record');

        $remedy = 'regenerate corpus.json with the pinned build: ' . $pin['install']
            . ' and python3 tools/sep-51-test-fixtures/generate_corpus.py';
        $this->assertSame($pin['version'], $oracle['version'],
            'corpus.json was generated by a build other than the pin; ' . $remedy);
        $this->assertSame($pin['xdr_commit'], $oracle['xdr_commit'],
            'corpus.json records an XDR revision other than the pin; ' . $remedy);
    }

    public function testInstallCommandNamesThePinnedVersion(): void
    {
        $pin = self::loadJson('oracle-pin.json');
        $this->assertSame(
            'cargo install stellar-xdr --features cli --version ' . $pin['version'] . ' --locked',
            $pin['install'],
            'oracle-pin.json install command must install the pinned version, '
            . 'which the generator prints as the remedy when the pinned build is missing'
        );
    }
}
